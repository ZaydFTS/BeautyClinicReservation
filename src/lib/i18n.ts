// ============================================================================
// Type-safe translation function
// ============================================================================

export type TranslationKeys = typeof translations.en

// Helper to get a nested value from an object using a dot-path
function getNestedValue(obj: unknown, path: string): string | undefined {
  const keys = path.split(".")
  let current: unknown = obj
  for (const key of keys) {
    if (current && typeof current === "object" && key in current) {
      current = (current as Record<string, unknown>)[key]
    } else {
      return undefined
    }
  }
  return typeof current === "string" ? current : undefined
}

export function translate(lang: Language, key: string, params?: Record<string, string | number>): string {
  const dict = translations[lang] as unknown as Record<string, unknown>
  const value = getNestedValue(dict, key)
  if (!value) {
    // Fall back to English
    const enDict = translations.en as unknown as Record<string, unknown>
    const enValue = getNestedValue(enDict, key)
    if (!enValue) return key
    return interpolate(enValue, params)
  }
  return interpolate(value, params)
}

function interpolate(s: string, params?: Record<string, string | number>): string {
  if (!params) return s
  return s.replace(/\{(\w+)\}/g, (_, k: string) => {
    const v = params[k]
    return v !== undefined ? String(v) : `{${k}}`
  })
}
